"use client";

import { useState } from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { ArrowRight, BookOpen, Sparkles } from "lucide-react";
import { Button } from "@/ui/easyui/Button";
import type { ChallengeView } from "../core/contracts";
import { challengeRequest } from "./challenge-api";

export function NewChallenge() {
  const router = useRouter();
  const [request, setRequest] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  async function create() {
    if (request.trim().length < 8 || busy) return;
    setBusy(true); setError("");
    try {
      const challenge = await challengeRequest<ChallengeView>("/api/challenges", "POST", { topicId: "custom", request: request.trim() });
      router.push(`/challenge/${challenge.id}`);
    } catch (failure) { setError((failure as Error).message); setBusy(false); }
  }
  return <div className="challenge-page"><div className="challenge-container new-challenge-page">
    <div className="challenge-eyebrow"><Sparkles size={16}/> MAKE IT YOURS</div>
    <h1>What do you want to learn?</h1>
    <p className="challenge-intro">Ask a question or name a topic. Neuroplast will build a boss quiz with four skills, score it, and give you targeted recall and application practice.</p>
    <section className="challenge-topic" aria-label="Create a topic challenge">
      <label className="new-challenge-label" htmlFor="challenge-request">Your topic or question</label>
      <textarea id="challenge-request" autoFocus maxLength={500} value={request} onChange={event => setRequest(event.target.value)} placeholder="For example: How do interest rates affect inflation? Or: I want to understand photosynthesis before my biology test."/>
      <div className="new-challenge-form-bottom"><span>{request.length}/500 · Be specific about what you want to practice.</span><Button onClick={() => void create()} disabled={request.trim().length < 8 || busy} isLoading={busy} rightIcon={<ArrowRight size={16}/>}>Build my quiz</Button></div>
      {error && <div className="new-challenge-error" role="alert"><p>{error}</p><Link href="/connections">Check model connection</Link></div>}
    </section>
    <div className="new-challenge-ready"><BookOpen size={18}/><div><strong>Want a ready-made chapter?</strong><p>Linear equations works without a model connection.</p></div><Button variant="secondary" onClick={() => router.push("/challenges")}>Choose linear equations</Button></div>
    <p className="challenge-footnote">Custom quiz questions and answer keys are generated by your connected model. Check explanations if an answer looks wrong.</p>
  </div></div>;
}
